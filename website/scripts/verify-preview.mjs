/**
 * Checks that a running build has a coherent deployment posture.
 *
 * ---------------------------------------------------------------------------
 * WHY THIS EXISTS
 * ---------------------------------------------------------------------------
 * "noindex" is not one switch. It is a robots.txt, a <meta name="robots">, an
 * X-Robots-Tag header and a sitemap, produced by four different parts of Next —
 * and the sitemap, /llms.txt and /og have no <head> to put a meta tag in, so
 * three of the four are needed to cover all of them. Any one of them silently
 * reverting puts a complete copy of the firm's site into the index on a
 * hostname that is not the firm's, and nobody finds out until it ranks.
 *
 * next.config.ts also cannot import src/config/deployment.ts — the Next CLI
 * loads it outside the application's module graph, so the "@/" alias does not
 * resolve and the SITE_ENV check is duplicated there. This asserts the two
 * copies agree, by checking that the header and the metadata say the same thing.
 *
 *   node scripts/verify-preview.mjs http://localhost:3199 preview
 *   node scripts/verify-preview.mjs https://fiatlaw.co.uk production
 */

const [, , base, expected = "preview"] = process.argv;

if (!base) {
  console.error("usage: node scripts/verify-preview.mjs <base-url> [preview|production]");
  process.exit(2);
}
if (expected !== "preview" && expected !== "production") {
  console.error(`unknown posture "${expected}" — expected "preview" or "production"`);
  process.exit(2);
}

const root = base.replace(/\/$/, "");
const wantNoIndex = expected === "preview";
const failures = [];
const notes = [];

function check(name, ok, detail) {
  (ok ? notes : failures).push(`${ok ? "ok  " : "FAIL"}  ${name}${detail ? ` — ${detail}` : ""}`);
}

async function get(path) {
  const res = await fetch(`${root}${path}`, { redirect: "manual" });
  return { status: res.status, headers: res.headers, body: await res.text() };
}

/* -------------------------------------------------------------- robots.txt */

const robots = await get("/robots.txt");
check("robots.txt serves", robots.status === 200, `HTTP ${robots.status}`);

const disallowsAll = /^\s*Disallow:\s*\/\s*$/m.test(robots.body);
const advertisesSitemap = /^\s*Sitemap:/m.test(robots.body);

// Scalix Shield generates /robots.txt at the edge from the project's bot
// policies and serves it in place of the application's. Worth naming rather
// than just failing a check: it means app/robots.ts is dead code on any Scalix
// Run deployment, and in production it silently drops the Sitemap line and the
// /admin and /api/ disallows.
const shieldOwnsRobots = /Scalix Shield/i.test(robots.body);
if (shieldOwnsRobots) {
  notes.push("note  /robots.txt is generated by Scalix Shield, not by app/robots.ts");
}

if (wantNoIndex) {
  // Either route out of the index is acceptable, and the second is the stronger
  // one. `Disallow: /` stops the crawler fetching the page, so it never reads
  // the noindex — and Google will still index a disallowed URL it finds linked
  // from somewhere else, listed with no snippet. Letting the crawl through so
  // the noindex is actually read is the documented way to stay out.
  check(
    "kept out of the index",
    disallowsAll || shieldOwnsRobots,
    disallowsAll ? "robots.txt disallows everything" : "crawl allowed; relies on X-Robots-Tag below",
  );
  // Only meaningful on the Disallow route: a sitemap is an invitation to crawl,
  // and advertising one while disallowing everything is a contradiction that
  // crawlers resolve in whichever direction they prefer.
  check("robots.txt advertises no sitemap", !advertisesSitemap || !disallowsAll);
} else {
  check("robots.txt does not disallow everything", !disallowsAll);
  check(
    "robots.txt advertises a sitemap",
    advertisesSitemap,
    shieldOwnsRobots ? "Shield's generated file has no Sitemap line — set it in the Shield policy" : "",
  );
}

/* ------------------------------------------------- X-Robots-Tag, everywhere */

// The surfaces that have no <head>: metadata cannot reach any of these, so the
// header is the only directive they will ever carry. /sitemap.xml matters most
// — a crawler that finds it has a complete list of every URL on the site.
const headless = ["/sitemap.xml", "/llms.txt", "/manifest.webmanifest", "/og?t=check", "/api/enquiry"];

for (const path of ["/", "/uk-entry-brief", "/india-uk/tariff-lookup", ...headless]) {
  const res = await get(path);
  const tag = res.headers.get("x-robots-tag");
  const noindex = (tag ?? "").toLowerCase().includes("noindex");
  check(
    `X-Robots-Tag ${wantNoIndex ? "present" : "absent"} on ${path}`,
    wantNoIndex ? noindex : !noindex,
    tag ? `got "${tag}"` : "header absent",
  );
}

/* -------------------------------------------------- <meta name="robots">    */

for (const path of ["/", "/contact", "/india-uk/tariff-lookup"]) {
  const res = await get(path);
  const meta = /<meta\s+name="robots"\s+content="([^"]*)"/i.exec(res.body)?.[1] ?? "";
  const noindex = meta.toLowerCase().includes("noindex");
  check(`meta robots ${wantNoIndex ? "noindex" : "index"} on ${path}`, wantNoIndex ? noindex : !noindex, `content="${meta}"`);
}

/* ------------------------------------------------------- canonical, banner  */

// Canonicals point at the real domain in both postures. If some crawler ignores
// every directive above, the strongest remaining signal should send it to
// fiatlaw.co.uk rather than let the preview host accumulate authority.
const home = await get("/");
const canonical = /<link\s+rel="canonical"\s+href="([^"]*)"/i.exec(home.body)?.[1] ?? "";
check("canonical points at fiatlaw.co.uk", canonical.startsWith("https://fiatlaw.co.uk"), `href="${canonical}"`);

const contact = await get("/contact");
const hasBanner = /Not the live site/.test(home.body);
const hasFormNotice = /written to\s+temporary storage|written to temporary storage/.test(contact.body);
check(`preview banner ${wantNoIndex ? "shown" : "absent"}`, wantNoIndex ? hasBanner : !hasBanner);
if (wantNoIndex) {
  // The banner is at the top of a long page; this is the notice that is on
  // screen at the moment somebody decides to press send.
  check("ephemeral-leads notice above the contact form", hasFormNotice);
}

/* -------------------------------------------------------------------- report */

for (const line of notes) console.log(line);
for (const line of failures) console.error(line);

console.log(`\n${notes.length} passed, ${failures.length} failed — posture "${expected}" at ${root}`);
process.exit(failures.length ? 1 : 0);
